def s(key, short, where, reward, guide, only=None):
    return (key, short, where, reward, guide if isinstance(guide, list) else [guide], only)


def dungeon(age, steps):
    out = []
    for key, short, where, reward, guide, only in steps:
        out.append(r("dg_" + key, short, "Dungeon step", age, "Any", "", where, reward, guide, short=short, only=only))
    return out


