# Main quest (story) steps for the Ocarina of Time tracker.
# Each step: key, name, kind, age, avail, start, reward, guide (hidden in the UI),
#   after (keys of steps that must be done first), gives (keys of rows that count as owned/learned once this is done).
# Order is the suggested route. `after` records what the game actually requires, so where the game
# lets you choose (Forest vs Fire, Shadow vs Spirit) the tracker does not force one order.
from side import SIDE


def _sq(i):
    for _n, _note, rows in SIDE:
        for r in rows:
            if r["id"] == i:
                return r


def m(key, name, kind, age, avail, start, reward, guide, after=(), gives=(), short=None, time="Any", v=None, needs=()):
    d = dict(key=key, name=name, kind=kind, age=age, time=time, avail=avail, start=start, reward=reward,
             guide=list(guide), after=list(after), gives=list(gives), short=short or name, needs=list(needs))
    if v:
        d["v"] = v
    return d


