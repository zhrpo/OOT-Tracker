import os as _os, sys as _sys; _sys.path.insert(0, _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '..', 'audit', 'lib')); import oot_env as _env  # Phase 0: repo-relative paths
from playwright.sync_api import sync_playwright
URL = _env.OUT_URL + "/themed2.html"
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=_env.CHROME, args=["--no-sandbox"])
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2)
    pg = ctx.new_page()
    pg.goto(URL + "#skulltulas/sw2")
    pg.wait_for_selector(".row")
    pg.screenshot(path="rev1_skull_top.png")
    pg.evaluate("document.getElementById('g5').scrollIntoView()")
    pg.wait_for_timeout(200)
    pg.screenshot(path="rev2_skull_mid.png")
    pg.goto(URL + "#sidequests/sw2")
    pg.wait_for_selector(".row")
    pg.evaluate("window.scrollTo(0, 900)")
    pg.wait_for_timeout(200)
    pg.screenshot(path="rev3_side_mid.png")
    h = pg.evaluate("document.body.scrollHeight")
    print("side page height:", h)
    pg.goto(URL + "#skulltulas/sw2")
    pg.wait_for_selector(".row")
    print("skull page height:", pg.evaluate("document.body.scrollHeight"), "rows:", pg.locator('.row').count(), "header h:", pg.evaluate("document.querySelector('.top').offsetHeight"))
    pg.goto(URL + "#hearts/sw2")
    pg.wait_for_selector(".row")
    print("heart page height:", pg.evaluate("document.body.scrollHeight"))
    b.close()
